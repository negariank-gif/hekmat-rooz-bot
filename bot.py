def get_sent_log():
    try:
        with open("sent_log.json", "r") as f:
            return json.load(f)
    except:
        return []

def save_sent_log(log):
    try:
        with open("sent_log.json", "w") as f:
            json.dump(log[-60:], f)
    except:
        pass

def send_post():
    sent_log = get_sent_log()
    available = [p for p in posts if p["mood"] + p["book"] not in sent_log]
    if not available:
        available = posts

    post = random.choice(available)
    sep = "━━━━━━━━━━━━━━━━━━"
    stars = DIFFICULTY.get(post["diff"], "⭐⭐⭐")

    message = (
        f"💊 <b>لیبرو درمانی</b>\n"
        f"{sep}\n\n"
        f"🩹 <b>{post['mood']}</b>\n\n"
        f"{post['intro']}\n\n"
        f"📖 این کتاب رو پیشنهاد می‌دم:\n"
        f"<b>{post['book']}</b> - {post['author']}\n"
        f"سختی مطالعه: {stars}\n\n"
        f"{sep}\n\n"
        f"<i>«{post['q1']}»</i>\n\n"
        f"و در جای دیگری از همین کتاب:\n\n"
        f"<i>«{post['q2']}»</i>\n\n"
        f"{sep}\n\n"
        f"💡 <b>توصیه امروز:</b>\n"
        f"{post['tip']}\n\n"
        f"{sep}\n\n"
        f"{post['end']}\n\n"
        f"{post['tags']}\n"
        f"📚 @sanchobook"
    )

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    response = requests.post(url, data={
        "chat_id": CHANNEL_ID,
        "text": message,
        "parse_mode": "HTML"
    })

    if response.status_code == 200:
        sent_log.append(post["mood"] + post["book"])
        save_sent_log(sent_log)
        print(f"ارسال شد: {post['mood']}")
    else:
        print(f"خطا: {response.text}")

if __name__ == "__main__":
    send_post()
