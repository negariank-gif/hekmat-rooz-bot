FLOWERS = ["🌸", "🌺", "🌹", "🍃", "🌾", "🌿", "❧", "✾", "❀", "🌻", "💐"]

def get_sent_log():
    try:
        with open("poem_log.json", "r") as f:
            return json.load(f)
    except:
        return []

def save_sent_log(log):
    try:
        with open("poem_log.json", "w") as f:
            json.dump(log[-50:], f)
    except:
        pass

def send_poem():
    sent_log = get_sent_log()
    available = [p for p in poems if p["verse"] not in sent_log]
    if not available:
        available = poems

    poem = random.choice(available)
    f1 = random.choice(FLOWERS)
    f2 = random.choice(FLOWERS)
    sep = f"{f1} ━━━━━━━━━━━━━━━ {f2}"

    message = (
        f"📜 <b>لیبرو | شعر</b>\n"
        f"{sep}\n\n"
        f"{poem['emoji']} <b>{poem['poet']}</b> {poem['emoji']}\n"
        f"از <b>{poem['book']}</b>\n\n"
        f"{sep}\n\n"
        f"<i>{poem['fact']}</i>\n\n"
        f"{sep}\n\n"
        f"<i>«{poem['verse']}»</i>\n\n"
        f"{sep}\n\n"
        f"{poem['reflection']}\n\n"
        f"✦ {poem['question']}\n\n"
        f"{sep}\n\n"
        f"📚 لیبرو درمانی\n"
        f"کتاب مناسبِ حال، نه حالِ مناسبِ کتاب.\n\n"
        f"{poem['tags']} #کتاب_درمانی #سلامت_روان"
    )

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    response = requests.post(url, data={
        "chat_id": CHANNEL_ID,
        "text": message,
        "parse_mode": "HTML"
    })

    if response.status_code == 200:
        sent_log.append(poem["verse"])
        save_sent_log(sent_log)
        print(f"ارسال شد: {poem['poet']}")
    else:
        print(f"خطا: {response.text}")

if __name__ == "__main__":
    send_poem()
