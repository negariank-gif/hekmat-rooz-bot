def get_sent_log():
    try:
        with open("sent_log.json", "r") as f:
            return json.load(f)
    except:
        return []

def save_sent_log(log):
    try:
        with open("sent_log.json", "w") as f:
            json.dump(log[-30:], f)
    except:
        pass

def get_time_category():
    now = datetime.datetime.utcnow()
    iran_hour = (now.hour + 3) % 24
    if iran_hour < 10:
        return "صبح"
    elif iran_hour >= 21:
        return "شب"
    return None

def send_quote():
    sent_log = get_sent_log()
    available = [q for q in quotes if q["text"] not in sent_log]
    if not available:
        available = quotes

    quote = random.choice(available)
    icon = ICONS.get(quote["cat"], "✨")

    separator = "━━━━━━━━━━━━━━━━━━"

    time_cat = get_time_category()
    if time_cat == "صبح":
        header = f"🌅 <b>حکمت صبحگاهی</b>"
    elif time_cat == "شب":
        header = f"🌃 <b>حکمت شبانه</b>"
    else:
        header = f"{icon} <b>حکمت روز</b>"

    message = (
        f"{header}\n"
        f"{separator}\n\n"
        f"<i>{quote['text']}</i>\n\n"
        f"— <b>{quote['author']}</b>\n\n"
        f"{separator}\n"
        f"{quote['tags']} #حکمت #عرفان\n"
        f"📖 @sanchobook"
    )

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    response = requests.post(url, data={
        "chat_id": CHANNEL_ID,
        "text": message,
        "parse_mode": "HTML"
    })

    if response.status_code == 200:
        sent_log.append(quote["text"])
        save_sent_log(sent_log)
        print(f"ارسال شد: {quote['author']}")
    else:
        print(f"خطا: {response.text}")

if __name__ == "__main__":
    send_quote()
