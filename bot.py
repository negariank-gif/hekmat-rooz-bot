def get_sent_log():
    try:
        with open("sent_log.json", "r") as f:
            return json.load(f)
    except:
        return []

def save_sent_log(log):
    try:
        with open("sent_log.json", "w") as f:
            json.dump(log[-50:], f)
    except:
        pass

def send_post():
    sent_log = get_sent_log()
    available = [p for p in posts if p["book"] not in sent_log]
    if not available:
        available = posts

    post = random.choice(available)
    separator = "━━━━━━━━━━━━━━━━━━"

    message = (
        f"💊 <b>لیبرو درمانی</b>\n"
        f"{separator}\n\n"
        f"اگه امروز <b>{post['pain']}</b> داری...\n\n"
        f"📖 بخوان: <b>{post['book']}</b>\n\n"
        f"{separator}\n\n"
        f"<i>{post['text']}</i>\n\n"
        f"{separator}\n"
        f"{post['tags']}\n"
        f"📚 @sanchobook"
    )

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    response = requests.post(url, data={
        "chat_id": CHANNEL_ID,
        "text": message,
        "parse_mode": "HTML"
    })

    if response.status_code == 200:
        sent_log.append(post["book"])
        save_sent_log(sent_log)
        print(f"ارسال شد: {post['pain']} - {post['book']}")
    else:
        print(f"خطا: {response.text}")

if __name__ == "__main__":
    send_post()
