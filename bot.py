def save_sent_log(log):
    try:
        with open("poem_log.json", "w") as f:
            json.dump(log[-50:], f)
    except:
        pass

def send_poem():
    sent_log = get_sent_log()
    available = [p for p in poems if p["verse"] not in sent_log]
    if not available:
        available = poems

    poem = random.choice(available)
    
    message = (
        f"📜 لیبرو | شعر\n\n"
        f"{poem['emoji']} {poem['poet']}\n"
        f"{poem['book']}\n\n"
        f"{poem['about']}\n\n"
        f"{poem['verse']}\n\n"
        f"📚 لیبرو درمانی\n"
        f"کتاب مناسبِ حال، نه حالِ مناسبِ کتاب.\n\n"
        f"{poem['tags']}"
    )

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    response = requests.post(url, data={
        "chat_id": CHANNEL_ID,
        "text": message,
        "parse_mode": "HTML"
    })

    if response.status_code == 200:
        sent_log.append(poem["verse"])
        save_sent_log(sent_log)
        print(f"ارسال شد: {poem['poet']} - {poem['book']}")
    else:
        print(f"خطا: {response.text}")

